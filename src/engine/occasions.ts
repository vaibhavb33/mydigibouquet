export const CORE_ELEVEN_OCCASIONS: readonly OccasionTemplateSpec[] = Object.values(OCCASION_TEMPLATES).filter(
  (item) => item.featuredCore,
);

export function applyOccasionTemplateToScene(
  current: BouquetSceneV1,
  slug: OccasionSlug,
  mode: "full" | "style-only",
  metaMap: ReadonlyMap<string, BotanicalMeta>,
): BouquetSceneV1 {
  const tpl = OCCASION_TEMPLATES[slug];
  let nextStems: StemInstance[] = current.stems;

  if (mode === "full") {
    const validSkus = tpl.recommendedSkuIds.filter((sku) => metaMap.has(sku));
    const seed = Date.now();
    const fresh: StemInstance[] = validSkus.map((skuId, idx) => ({
      id: `stem-occ-${slug}-${seed}-${idx}`,
      skuId,
      x: 500,
      y: 420,
      scale: 1,
      rotationDeg: 0,
      flippedX: false,
      zIndex: idx,
      locked: false,
    }));
    nextStems = arrangeBouquetByPreset(fresh, tpl.compositionPreset, metaMap);
  }

  return {
    ...current,
    occasionTag: slug,
    stems: nextStems,
    presentation: normalizePresentationConfig({
      vesselId: tpl.vesselId,
      bowStyleId: tpl.bowStyleId,
      ribbonFinishId: tpl.ribbonFinishId,
      ribbonColorId: tpl.ribbonColorId,
      stemVisibility: current.presentation.stemVisibility,
      tableSurfaceId: tpl.tableSurfaceId,
      compositionPreset: mode === "full" ? tpl.compositionPreset : current.presentation.compositionPreset,
    }),
    card: {
      ...current.card,
      templateId: tpl.cardTemplateId,
      envelopeId: tpl.cardTemplateId,
      paperTintId: tpl.paperTintId,
      textColorId: tpl.textColorId,
      waxSealColorId: tpl.waxSealColorId,
      fontPairingId: tpl.fontPairingId,
      message:
        current.card.message.trim().length === 0 || mode === "full"
          ? tpl.sampleMessage
          : current.card.message,
    },
  };
}

